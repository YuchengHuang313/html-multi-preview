const vscode = require('vscode');
const assert = require('node:assert/strict');
exports.run = async () => {
  const all = () => vscode.window.tabGroups.all.flatMap(g => g.tabs);
  const rendered = () => all().filter(t => t.input instanceof vscode.TabInputCustom && t.input.viewType === 'htmlMultiPreview.rendered');
  const root = vscode.workspace.workspaceFolders[0].uri;
  const a = vscode.Uri.joinPath(root, 'a.html');
  const b = vscode.Uri.joinPath(root, 'b.html');
  await vscode.extensions.getExtension('yhuang546.html-multi-preview').activate();
  await vscode.window.tabGroups.close(all());
  await vscode.commands.executeCommand('vscode.openWith', a, 'default', {preview: false});
  const group = vscode.window.tabGroups.activeTabGroup.viewColumn;
  await vscode.commands.executeCommand('htmlMultiPreview.showNewPreview');
  assert.equal(rendered().length, 1);
  assert.equal(all().length, 1, 'Render replaces clean source');
  assert.equal(rendered()[0].group.viewColumn, group);
  const original = rendered()[0];
  await Promise.all(Array.from({length: 5}, () => vscode.commands.executeCommand('htmlMultiPreview.showNewPreview', a)));
  assert.equal(rendered().length, 1, 'rapid clicks reuse preview');
  assert.equal(rendered()[0], original, 'preview identity is preserved');
  await vscode.commands.executeCommand('vscode.openWith', b, 'default', {viewColumn: vscode.ViewColumn.Beside, preview: false});
  await vscode.commands.executeCommand('htmlMultiPreview.showNewPreview', b);
  assert.equal(rendered().length, 2, 'different pages stay separate');
  await vscode.commands.executeCommand('htmlMultiPreview.showNewPreview', a);
  assert.equal(vscode.window.tabGroups.activeTabGroup.activeTab.input.uri.toString(), a.toString(), 'existing page is focused');
  assert.equal(vscode.window.tabGroups.activeTabGroup.viewColumn, group, 'focus returns to original group');
  assert.equal(rendered().length, 2);
  await vscode.commands.executeCommand('vscode.openWith', a, 'default', {preview: false});
  const editor = vscode.window.activeTextEditor;
  await editor.edit(e => e.insert(new vscode.Position(0, 0), '<!-- unsaved -->'));
  await vscode.commands.executeCommand('htmlMultiPreview.showNewPreview', a);
  assert.ok(editor.document.isDirty, 'Render preserves unsaved edits');
  assert.ok(editor.document.getText().startsWith('<!-- unsaved -->'));
  await vscode.commands.executeCommand('vscode.openWith', a, 'default');
  await vscode.commands.executeCommand('workbench.action.files.revert');
  await vscode.window.tabGroups.close(all());
  console.log('PASS: replacement, reuse, concurrent clicks, cross-group focus, distinct pages, dirty-buffer preservation');
};
